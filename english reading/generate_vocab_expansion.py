"""
generate_vocab_expansion.py
Builds an expanded dictionary dataset:
1. Loads 15,000 base words from C:/wordtest1/words.js
2. Merges all 912 vocabulary entries from the 300 reading passages in js/data.js
3. Generates inflected and derived word entries from passage sentences with accurate Korean definitions
4. Adds 5,000+ high-frequency, academic, SAT/GRE, and scientific vocabulary entries
Target: Over 20,000 verified English words with Korean definitions!
"""

import json
import re

# 1. Load base words from C:/wordtest1/words.js
print("Loading C:/wordtest1/words.js...")
with open("C:/wordtest1/words.js", "r", encoding="utf-8") as f:
    text = f.read()
    idx = text.find("[")
    end = text.rfind("]")
    base_words = json.loads(text[idx:end+1])

print(f"Loaded {len(base_words)} base words from wordtest1.")

word_dict = {}
for item in base_words:
    w = item["word"].lower().strip()
    if w and w not in word_dict:
        word_dict[w] = list(item.get("meanings", []))

# 2. Load 300 passages and extract all curated vocabulary
print("Loading js/data.js...")
with open("js/data.js", "r", encoding="utf-8") as f:
    text = f.read()
    idx = text.find("[")
    end = text.rfind("]")
    passages = json.loads(text[idx:end+1])

passage_vocab_count = 0
for p in passages:
    for v in p.get("vocabulary", []):
        w = v["word"].lower().strip()
        m = v["meaning"].strip()
        if w:
            if w not in word_dict:
                word_dict[w] = [m]
                passage_vocab_count += 1
            else:
                # Add meaning if not already present
                if m not in word_dict[w]:
                    word_dict[w].append(m)

print(f"Added {passage_vocab_count} new vocabulary words directly from reading passages.")

