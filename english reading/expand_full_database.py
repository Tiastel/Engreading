# Adverbs from adjectives
adv_added = 0
for w, meanings in list(word_dict.items()):
    m0 = meanings[0] if meanings else ""
    if any(m0.endswith(suff) for suff in ["한", "인", "의", "로운", "적인", "된"]):
        adv = None
        if w.endswith("y") and not w.endswith("ly"): adv = w[:-1] + "ily"
        elif w.endswith("ic"): adv = w + "ally"
        elif not w.endswith("ly"): adv = w + "ly"
        if adv and adv not in word_dict and len(adv) >= 4 and re.match(r"^[a-z]+$", adv):
            kor_adv = m0
            if kor_adv.endswith("한"): kor_adv = kor_adv[:-1] + "하게"
            elif kor_adv.endswith("인"): kor_adv = kor_adv[:-1] + "으로"
            elif kor_adv.endswith("로운"): kor_adv = kor_adv[:-2] + "럽게"
            elif kor_adv.endswith("적인"): kor_adv = kor_adv[:-2] + "적으로"
            else: kor_adv = kor_adv + "하게"
            word_dict[adv] = [kor_adv]
            adv_added += 1

print(f"Added {adv_added} regular adverbs.")

